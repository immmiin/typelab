import { open, S, L, check } from './lib.mjs'
const { b, p, errs } = await open()
let st = await S(p)
check(st.sel.length === 1, 'headline auto-selected on load')
await p.screenshot({ path: '/tmp/shots/n-1.png' })
// deselect then pick a font -> applies to headline
await p.keyboard.press('Escape')
await p.locator('[data-section="font"] button[aria-expanded]').click()
await p.locator('[data-testid="font-fraunces"]').first().click()
let h = await L(p, 'Headline'); check(h.style.fontId === 'fraunces', 'font pick with no selection targets headline')
// family picker popover + style chip
await p.locator('[data-testid="family-field"]').click()
await p.screenshot({ path: '/tmp/shots/n-2.png' })
await p.locator('[data-testid="font-picker"] [aria-label="Show styles of Archivo"]').click()
await p.locator('[data-testid="styles-archivo"] button').nth(2).click()
h = await L(p, 'Headline'); check(h.style.fontId === 'archivo', 'style chip applies family+style: ' + h.style.weight)
// grid menu
await p.locator('[data-tool="grid"]').click()
await p.screenshot({ path: '/tmp/shots/n-3.png' })
await p.locator('[data-testid="grid-menu"] [data-grid-preset="8pt"]').click()
st = await S(p); check(st.doc.grid.show && st.doc.grid.type === 'uniform' && st.doc.grid.size === 8, '8pt preset')
await p.keyboard.press('Escape')
await p.mouse.click(1300, 900 - 30)
await p.screenshot({ path: '/tmp/shots/n-4.png' })
await p.locator('[data-tool="grid"]').click()
await p.locator('[data-testid="grid-menu"] [data-grid-preset="m8"]').click()
await p.screenshot({ path: '/tmp/shots/n-5.png' })
console.log('errors', errs.join('\n'))
await b.close()
