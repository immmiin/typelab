import { open, S, L, check } from './lib.mjs'
const { b, p, errs } = await open()
const n0 = (await S(p)).doc.layers.length
// --- keyboard: select headline, duplicate, delete
await p.mouse.click(600, 420)
await p.keyboard.press('Control+d')
check((await S(p)).doc.layers.length === n0 + 1, 'Cmd+D duplicate')
await p.keyboard.press('Delete')
check((await S(p)).doc.layers.length === n0, 'Delete removes')
// arrows
await p.mouse.click(600, 420)
let h = await L(p, 'Headline'); const x0 = h.x
await p.keyboard.press('ArrowRight'); await p.keyboard.press('Shift+ArrowRight')
h = await L(p, 'Headline'); check(h.x === x0 + 11, 'arrow nudge 1 + shift 10 -> ' + (h.x - x0))
// select all + group + ungroup
await p.keyboard.press('Control+a'); check((await S(p)).sel.length === n0, 'Cmd+A select all')
await p.keyboard.press('Escape'); check((await S(p)).sel.length === 0, 'Esc deselects')
await p.mouse.click(600, 420); await p.keyboard.down('Shift'); await p.mouse.click(500, 155); await p.keyboard.up('Shift')
check((await S(p)).sel.length === 2, 'shift-click multi select')
await p.keyboard.press('Control+g')
let st = await S(p)
check(Object.keys(st.doc.groups).length === 1 && st.doc.layers.filter(l => l.groupId).length === 2, 'Cmd+G group')
await p.keyboard.press('Escape'); await p.mouse.click(600, 420)
check((await S(p)).sel.length === 2, 'clicking grouped layer selects group')
await p.keyboard.press('Control+Shift+g')
st = await S(p); check(Object.keys(st.doc.groups).length === 0, 'Shift+Cmd+G ungroup')
// align / distribute
await p.keyboard.press('Escape'); await p.mouse.click(600, 420)
await p.locator('[data-tab="form"]').click()
await p.locator('button[data-tip^="Align right"]').first().click()
h = await L(p, 'Headline'); const A = st.doc.artboard
check(h.x > 100, 'align right to artboard x=' + h.x.toFixed(0))
await p.keyboard.press('Control+z')
await p.keyboard.press('Control+a')
await p.locator('button[data-tip^="Distribute vertically"]').first().click()
await p.keyboard.press('Control+z')
await p.keyboard.press('Escape')
// --- layers panel: rename, hide, lock, reorder
await p.locator('[data-testid="layer-row-Caption"]').dblclick()
await p.locator('input[aria-label="Layer name"]').fill('Footnote'); await p.keyboard.press('Enter')
check(!!(await L(p, 'Footnote')), 'rename layer')
await p.locator('[data-testid="layer-row-Footnote"]').hover()
await p.locator('[data-testid="layer-row-Footnote"] button[aria-label="Hide layer"]').click()
check((await L(p, 'Footnote')).visible === false, 'hide layer')
await p.locator('[data-testid="layer-row-Footnote"] button[aria-label="Show layer"]').click()
await p.locator('[data-testid="layer-row-Footnote"]').hover()
await p.locator('[data-testid="layer-row-Footnote"] button[aria-label="Lock layer"]').click()
check((await L(p, 'Footnote')).locked === true, 'lock layer')
await p.locator('[data-testid="layer-row-Footnote"] button[aria-label="Unlock layer"]').click()
const order0 = (await S(p)).doc.layers.map(l => l.name).join(',')
await p.locator('[data-testid="layer-row-Rule"]').dragTo(p.locator('[data-testid="layer-row-Headline"]'))
const order1 = (await S(p)).doc.layers.map(l => l.name).join(',')
check(order1.endsWith('Rule') || order1.split(',').at(-2) === 'Rule' || order0 !== order1, `drag reorder: ${order0} -> ${order1}`)
// --- guides from rulers
const g0 = (await S(p)).doc.guides.length
await p.mouse.move(700, 54); await p.mouse.down(); await p.mouse.move(700, 200, { steps: 6 }); await p.mouse.up()
st = await S(p); check(st.doc.guides.length === g0 + 1 && st.doc.guides.at(-1).axis === 'y', 'drag guide from top ruler')
// drag it back to ruler -> delete
const gy = st.doc.guides.at(-1).pos * st.view.zoom + st.view.panY + 44
await p.mouse.move(800, gy); await p.mouse.down(); await p.mouse.move(800, 50, { steps: 6 }); await p.mouse.up()
check((await S(p)).doc.guides.length === g0, 'drag guide back to ruler deletes')
// --- grid tool G
await p.keyboard.press('g'); check((await S(p)).doc.grid.show, 'G toggles grid')
await p.screenshot({ path: '/tmp/shots/y-grid.png' })
await p.keyboard.press('g')
// --- shape tool
await p.keyboard.press('u')
await p.mouse.move(500, 600); await p.mouse.down(); await p.mouse.move(620, 700, { steps: 5 }); await p.mouse.up()
st = await S(p); const sh = st.doc.layers.at(-1)
check(sh.type === 'shape' && sh.w > 150, 'shape tool draws rect ' + sh.w.toFixed(0))
await p.keyboard.press('Delete')
// --- type tool click on empty
await p.keyboard.press('t')
await p.mouse.click(700, 650)
await p.keyboard.type('Fresh')
st = await S(p); const nt = st.doc.layers.at(-1)
check(nt.type === 'text' && nt.text === 'Fresh' && st.editing === nt.id, 'type tool creates + edits text: ' + nt.text)
await p.keyboard.press('Escape')
// --- scale tool drag
await p.keyboard.press('Escape'); await p.keyboard.press('v'); await p.mouse.click(600, 420); await p.keyboard.press('s')
await p.mouse.move(800, 480); await p.mouse.down(); await p.mouse.move(880, 520, { steps: 6 }); await p.mouse.up()
h = await L(p, 'Headline'); check(h.scaleX > 1.05, 'scale tool scaleX=' + h.scaleX)
await p.keyboard.press('Control+z')
// --- rotate tool drag
await p.keyboard.press('r')
await p.mouse.move(850, 420); await p.mouse.down(); await p.mouse.move(820, 520, { steps: 6 }); await p.mouse.up()
h = await L(p, 'Headline'); check(Math.abs(h.rotation) > 5, 'rotate tool ' + h.rotation)
await p.keyboard.press('Control+z')
// --- warp tool drag
await p.keyboard.press('w')
await p.mouse.move(600, 420); await p.mouse.down(); await p.mouse.move(720, 400, { steps: 6 }); await p.mouse.up()
h = await L(p, 'Headline'); check(h.distort.warp === 'arc' && h.distort.bend > 20, `warp tool bend=${h.distort.bend} int=${h.distort.intensity}`)
await p.screenshot({ path: '/tmp/shots/y-warptool.png' })
await p.keyboard.press('Control+z'); await p.keyboard.press('Control+z')
// --- path tool click on text
await p.keyboard.press('p')
await p.mouse.click(600, 420)
h = await L(p, 'Headline'); check(h.path.enabled, 'path tool enables text on path')
await p.keyboard.press('Control+z')
// --- char mode: drag a glyph
await p.keyboard.press('v'); await p.keyboard.press('Escape'); await p.mouse.click(600, 420)
await p.keyboard.press('c')
check((await S(p)).charMode, 'C toggles glyph mode')
await p.mouse.move(493, 400); await p.mouse.down(); await p.mouse.move(493, 340, { steps: 6 }); await p.mouse.up()
h = await L(p, 'Headline'); check(h.chars[0] && h.chars[0].dy < -50, 'glyph drag moves T: ' + JSON.stringify(h.chars[0]))
await p.screenshot({ path: '/tmp/shots/y-charmode.png' })
await p.keyboard.press('c')
// --- glyph panel insert
await p.mouse.dblclick(600, 420)
await p.keyboard.press('End')
await p.locator('[aria-label="Glyphs"]').first().click()
await p.locator('[data-glyph="8364"]').click()
h = await L(p, 'Headline'); check(h.text.endsWith('€'), 'glyph insert € -> ' + JSON.stringify(h.text))
await p.screenshot({ path: '/tmp/shots/y-glyphs.png' })
await p.locator('[aria-label="Close glyphs"]').click()
await p.keyboard.press('Escape')
// --- presets
await p.mouse.click(600, 420)
await p.locator('[data-tab="type"]').click()
await p.locator('[data-testid="preset-POSTER"]').click()
h = await L(p, 'Headline'); check(h.style.fontId === 'archivo' && h.style.textCase === 'upper', 'POSTER preset applied')
await p.screenshot({ path: '/tmp/shots/y-poster.png' })
// --- generate
const before = JSON.stringify((await L(p, 'Headline')).style)
await p.locator('[data-testid="generate"]').click()
const after = JSON.stringify((await L(p, 'Headline')).style)
check(before !== after, 'GENERATE changed style')
await p.screenshot({ path: '/tmp/shots/y-generate.png' })
// --- canvas preset & units
await p.locator('[data-tab="doc"]').click()
await p.locator('select[aria-label="Artboard preset"]').selectOption('a4')
st = await S(p); check(Math.round(st.doc.artboard.w) === 595 && st.doc.unit === 'mm', 'A4 preset + mm units')
await p.screenshot({ path: '/tmp/shots/y-a4.png' })
// --- shortcuts modal
await p.keyboard.press('?')
check(await p.locator('[data-testid="shortcuts"]').isVisible(), 'shortcut modal')
await p.screenshot({ path: '/tmp/shots/y-keys.png' })
await p.keyboard.press('Escape')
// --- modes
await p.locator('[data-mode="specimen"]').click(); await p.waitForTimeout(300)
await p.screenshot({ path: '/tmp/shots/y-specimen.png' })
await p.locator('[data-testid="specimen"] .tl-scroll').evaluate(e => e.scrollTop = 1400)
await p.screenshot({ path: '/tmp/shots/y-specimen2.png' })
await p.locator('[data-mode="compare"]').click(); await p.waitForTimeout(300)
await p.screenshot({ path: '/tmp/shots/y-compare.png' })
await p.locator('[data-testid="compare"] [role="radio"]:has-text("Overlay")').click()
await p.screenshot({ path: '/tmp/shots/y-overlay.png' })
console.log('errors:', errs.join('\n'))
await b.close()
