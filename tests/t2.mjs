import { open, S, L, check } from './lib.mjs'
const { b, p, errs } = await open()
let h0 = await L(p, 'Headline')
const z = (await S(p)).view.zoom
// A move
await p.mouse.move(600, 420); await p.mouse.down(); await p.mouse.move(650, 445, { steps: 5 }); await p.mouse.move(700, 470, { steps: 5 }); await p.mouse.up()
let h1 = await L(p, 'Headline')
check(Math.abs((h1.x - h0.x) - 100 / z) < 12 && Math.abs((h1.y - h0.y) - 50 / z) < 12, `move dx=${(h1.x-h0.x).toFixed(1)} dy=${(h1.y-h0.y).toFixed(1)} expected ~${(100/z).toFixed(1)}`)
// B resize east handle
const sel = await p.locator('[data-h="e"]').boundingBox()
await p.mouse.move(sel.x + 4, sel.y + 4); await p.mouse.down(); await p.mouse.move(sel.x - 150, sel.y + 4, { steps: 8 }); await p.mouse.up()
let h2 = await L(p, 'Headline')
check(h2.autoWidth === false && h2.w < h1.w + 1000, `resize -> autoWidth=${h2.autoWidth} w=${h2.w.toFixed(0)}`)
const lines = await p.evaluate(() => document.querySelectorAll('[data-layer] text').length)
await p.screenshot({ path: '/tmp/shots/05-resize.png' })
// C rotate via handle zone (offset outside ne corner)
const ne = await p.locator('[data-h="ne"]').boundingBox()
await p.mouse.move(ne.x + 14, ne.y - 6); await p.mouse.down(); await p.mouse.move(ne.x + 14, ne.y + 80, { steps: 10 }); await p.mouse.up()
let h3 = await L(p, 'Headline')
check(Math.abs(h3.rotation) > 2, `rotate -> ${h3.rotation}`)
await p.screenshot({ path: '/tmp/shots/06-rot.png' })
// D undo x3
await p.keyboard.press('Control+z'); await p.keyboard.press('Control+z'); await p.keyboard.press('Control+z')
let h4 = await L(p, 'Headline')
check(h4.x === h0.x && h4.rotation === 0 && h4.autoWidth === true, `undo restores x=${h4.x} rot=${h4.rotation} auto=${h4.autoWidth}`)
await p.keyboard.press('Control+Shift+z')
let h5 = await L(p, 'Headline')
check(h5.x !== h0.x, 'redo re-applies move')
await p.keyboard.press('Control+z')
// E edit text
await p.mouse.dblclick(600, 420)
await p.waitForTimeout(150)
let s = await S(p)
check(s.editing === h0.id, 'double-click enters edit mode')
await p.keyboard.press('Control+a')
await p.keyboard.type('HELLO')
await p.keyboard.press('Enter')
await p.keyboard.type('WORLD')
let h6 = await L(p, 'Headline')
check(h6.text === 'HELLO\nWORLD', `typed text = ${JSON.stringify(h6.text)}`)
await p.keyboard.press('Shift+ArrowLeft'); await p.keyboard.press('Shift+ArrowLeft'); await p.keyboard.press('Shift+ArrowLeft')
s = await S(p)
check(Math.abs(s.textSel[0] - s.textSel[1]) === 3, `selection range ${s.textSel}`)
await p.screenshot({ path: '/tmp/shots/07-edit.png' })
// F char style via character section: size field
await p.locator('[data-section="character"]').scrollIntoViewIfNeeded()
const sizeInput = p.locator('[data-section="character"] input[aria-label="Size"]')
await sizeInput.fill('260'); await sizeInput.press('Enter')
const colorInput = p.locator('[data-section="character"] input[aria-label="Hex colour"]')
await colorInput.fill('#2b2bff')
let h7 = await L(p, 'Headline')
check(h7.chars[8]?.size === 260 && h7.chars[9]?.color === '#2b2bff' && !h7.chars[0], `char styles on range: ${JSON.stringify(h7.chars.slice(7,11))}`)
await p.keyboard.press('Escape')
await p.screenshot({ path: '/tmp/shots/08-chars.png' })
console.log('errors:', errs.join('\n'))
await b.close()
