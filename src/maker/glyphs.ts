// Default glyph drawings for the Font Maker.
// Each glyph is a grid of cells, 7 rows tall (cap height). '#' = filled, '.' = empty.
// Width is the length of each row, so narrow letters (I, 1, punctuation) just use fewer columns.

export const ROWS = 7

export type GlyphRows = string[]

const g = (s: string): GlyphRows => s.trim().split(/\s+/)

